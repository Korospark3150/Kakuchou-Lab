/*
  ロゴ設定ファイル
  ------------------------------------------------------------
  ここに base64 のロゴを貼り付けると、
  ・ブラウザのタブのアイコン(favicon)
  ・サイト内のロゴ(ヘッダー / ヒーロー / フッター)
  のすべてが自動で差し替わります。

  使い方:
   1) LOGO_BASE64 に base64文字列を貼る(中身だけでも、"data:image/png;base64,..." の形でもOK)
   2) 画像が PNG 以外なら LOGO_MIME を変える(例: "image/svg+xml", "image/jpeg", "image/webp")

  空のままなら、同じフォルダの logo.svg が使われます。
*/
window.LOGO_BASE64 = "";
window.LOGO_MIME = "image/png";
